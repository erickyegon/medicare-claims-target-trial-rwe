"""Generate the SAS programs that load the CMS synthetic files, so column positions are never typed by hand:
  sas/download_raw.sas   PROC HTTP download of the 14 public CMS files needed (into &RAW)
  sas/import_raw.sas     reads only the needed columns (by position found from the file headers) from the pipe-delimited files, including
                         Carrier.zip / Outpatient.zip read in place; every field is character (keeps leading zeros)
Run from the project root:  python sas/build/gen_sas_import.py        (needs data/raw for the headers and data/urls.txt)"""
import pathlib
root = pathlib.Path(__file__).resolve().parents[2]
raw = root / "data/raw"
dx = lambda k: ["PRNCPAL_DGNS_CD"] + [f"ICD_DGNS_CD{i}" for i in range(1, k + 1)]
TABLES = [  # (sas dataset, [(file name in &RAW, zip member or None, local header file)], needed columns)
    ("bene_raw", [(f"beneficiary_{y}.csv", None, raw / f"beneficiary_{y}.csv") for y in range(2015, 2024)],
     ["BENE_ID", "BENE_ENROLLMT_REF_YR", "BENE_BIRTH_DT", "SEX_IDENT_CD"] + [f"MDCR_ENTLMT_BUYIN_IND_{m:02d}" for m in range(1, 13)] + [f"PTD_CNTRCT_ID_{m:02d}" for m in range(1, 13)]),
    ("carrier_raw", [("Carrier.zip", "carrier.csv", raw / "carrier/carrier.csv")], ["BENE_ID", "CLM_ID", "CLM_FROM_DT"] + dx(12)),
    ("outpatient_raw", [("Outpatient.zip", "outpatient.csv", raw / "outpatient/outpatient.csv")], ["BENE_ID", "CLM_ID", "CLM_FROM_DT"] + dx(25)),
    ("inpatient_raw", [("inpatient.csv", None, raw / "inpatient.csv")], ["BENE_ID", "CLM_ID", "CLM_FROM_DT", "CLM_ADMSN_DT", "CLM_THRU_DT"] + dx(25)),
    ("pde_raw", [("pde.csv", None, raw / "pde.csv")], ["BENE_ID", "SRVC_DT", "PROD_SRVC_ID"]),
    ("hospice_raw", [("hospice.csv", None, raw / "hospice.csv")], ["BENE_ID", "CLM_FROM_DT", "CLM_THRU_DT"]),
]
out = ["/* GENERATED by sas/build/gen_sas_import.py - do not edit by hand.",
       "   Reads only the columns the QC programs need, by position (scan with the M modifier keeps empty fields), all as character.",
       "   Requires &RAW to hold the files fetched by download_raw.sas. */", ""]
for ds, files, keep in TABLES:
    header = open(files[0][2], encoding="utf-8").readline().strip().split("|")
    missing = [c for c in keep if c not in header]
    assert not missing, (ds, missing)
    pos = {c: header.index(c) + 1 for c in keep}
    base = {"bene_raw": "bn", "carrier_raw": "cr", "outpatient_raw": "op", "inpatient_raw": "ip", "pde_raw": "pd", "hospice_raw": "hs"}[ds]   # filerefs: max 8 characters
    if len(files) > 1:   # several files read as one stream: the list takes quoted physical names only
        out.append(f"filename {base}_f (" + " ".join(f'"&RAW/{f}"' for f, _, _ in files) + ");")
        src = f"{base}_f"
    else:
        fname, member, _ = files[0]
        out.append(f'filename {base}0 zip "&RAW/{fname}" member="{member}";' if member else f'filename {base}0 "&RAW/{fname}";')
        src = f"{base}0"
    out.append(f"data {ds};")
    out.append(f"  infile {src} lrecl=32767 truncover;")
    out.append("  length " + " ".join(keep) + " $64;")
    out.append("  input;")
    out.append(f"  if scan(_infile_, 1, '|', 'm') = '{header[0]}' then delete;")
    for c in keep: out.append(f"  {c} = scan(_infile_, {pos[c]}, '|', 'm');")
    out.append("run;")
    out.append(f"proc sql noprint; select count(*) into :n_{ds} trimmed from {ds}; quit;")
    out.append(f"%put NOTE: {ds} rows = &n_{ds};")
    out.append("")
(root / "sas/import_raw.sas").write_text("\n".join(out), encoding="utf-8")

# ---- download program ----
need = {f for ds, files, _ in TABLES for f, _, _ in files}
urls = [l.split() for l in (root / "data/urls.txt").read_text().splitlines() if l.strip()]
dl = ["/* GENERATED by sas/build/gen_sas_import.py. Downloads the public CMS synthetic files (about 210 MB) to &RAW with PROC HTTP (OUT= takes a fileref). */",
      "%macro dl(name, url); filename _dl \"&RAW/&name\"; proc http url=\"&url\" out=_dl method=\"get\"; run; filename _dl clear; %mend;"]
for name, url in urls:
    if name in need:
        dl.append(f"%dl({name}, {url})")
dl.append("%put NOTE: download finished;")
(root / "sas/download_raw.sas").write_text("\n".join(dl) + "\n", encoding="utf-8")
print("wrote sas/import_raw.sas and sas/download_raw.sas;", len(need), "files")
