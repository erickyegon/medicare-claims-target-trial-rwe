"""Generate sas/import_raw.sas from the headers of the raw pipe-delimited CMS files, so column order is never typed by hand.
Every field is read as character (keeps leading zeros in NDC and codes); only the columns the QC programs need are kept.
Run from the project root:  python sas/build/gen_sas_import.py"""
import pathlib
root = pathlib.Path(__file__).resolve().parents[2]
raw = root / "data/raw"
dx = lambda k: ["PRNCPAL_DGNS_CD"] + [f"ICD_DGNS_CD{i}" for i in range(1, k + 1)]
TABLES = [  # (sas dataset, files, keep columns)
    ("bene_raw", [raw / f"beneficiary_{y}.csv" for y in range(2015, 2024)],
     ["BENE_ID", "BENE_ENROLLMT_REF_YR", "BENE_BIRTH_DT", "SEX_IDENT_CD"] + [f"MDCR_ENTLMT_BUYIN_IND_{m:02d}" for m in range(1, 13)] + [f"PTD_CNTRCT_ID_{m:02d}" for m in range(1, 13)]),
    ("carrier_raw", [raw / "carrier/carrier.csv"], ["BENE_ID", "CLM_ID", "CLM_FROM_DT"] + dx(12)),
    ("outpatient_raw", [raw / "outpatient/outpatient.csv"], ["BENE_ID", "CLM_ID", "CLM_FROM_DT"] + dx(25)),
    ("inpatient_raw", [raw / "inpatient.csv"], ["BENE_ID", "CLM_ID", "CLM_FROM_DT", "CLM_ADMSN_DT", "CLM_THRU_DT"] + dx(25)),
    ("pde_raw", [raw / "pde.csv"], ["BENE_ID", "SRVC_DT", "PROD_SRVC_ID"]),
    ("hospice_raw", [raw / "hospice.csv"], ["BENE_ID", "CLM_FROM_DT", "CLM_THRU_DT"]),
]
out = ["/* GENERATED by sas/build/gen_sas_import.py - do not edit by hand.",
       "   Reads the CMS synthetic files (pipe-delimited, header row) with every field as character.",
       "   Requires &RAW to point at the folder holding beneficiary_20xx.csv, pde.csv, inpatient.csv, hospice.csv, carrier/carrier.csv, outpatient/outpatient.csv. */", ""]
for ds, files, keep in TABLES:
    header = open(files[0], encoding="utf-8").readline().strip().split("|")
    missing = [c for c in keep if c not in header]
    assert not missing, (ds, missing)
    fref = ds.replace("_raw", "") + "_f"
    paths = " ".join('"&RAW/' + str(f.relative_to(raw)).replace("\\", "/") + '"' for f in files)
    out.append(f"filename {fref} ({paths});")
    out.append(f"data {ds}(keep={' '.join(keep)});")
    out.append(f"  infile {fref} dlm='|' dsd truncover lrecl=32767;")
    out.append("  length " + " ".join(header) + " $64;")
    out.append("  input " + " ".join(header) + ";")
    out.append(f"  if {header[0]} = '{header[0]}' then delete;   /* header row of each file */")
    out.append("run;")
    out.append(f"filename {fref} clear;")
    out.append(f"proc sql noprint; select count(*) into :n_{ds} trimmed from {ds}; quit;")
    out.append(f"%put NOTE: {ds} rows = &n_{ds};")
    out.append("")
(root / "sas/import_raw.sas").write_text("\n".join(out), encoding="utf-8")
print("wrote sas/import_raw.sas with", len(TABLES), "tables")
