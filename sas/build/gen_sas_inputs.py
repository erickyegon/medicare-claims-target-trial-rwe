"""Generate sas/inputs_codelists.sas: the small reference inputs the SAS QC program needs, written as in-program datalines so nothing has to be
uploaded to SAS OnDemand. Contents (all non-identifying): the NDC-to-antihypertensive-class map, the ICD-10 hypertension codes, and the R
attrition and baseline counts that the SAS results are reconciled against. Creates libname RWE (permanent) under the user's home folder.
Run from the project root:  python sas/build/gen_sas_inputs.py"""
import pathlib
import pandas as pd
root = pathlib.Path(__file__).resolve().parents[2]
ndc = pd.read_csv(root / "codelists/ndc_antihypertensive.csv", dtype=str)[["ndc11", "ahtn_class"]].drop_duplicates()
htn = pd.read_csv(root / "codelists/icd10_hypertension.csv", dtype=str)["icd10_code"].tolist()
att = pd.read_csv(root / "qc/cohort/attrition.csv")
base = pd.read_csv(root / "qc/cohort/cohort_baseline_counts.csv", dtype=str)
L = ["/* GENERATED by sas/build/gen_sas_inputs.py - do not edit by hand. Small reference inputs for sas/cohort_qc.sas. */",
     "%let ROOT = /home/&sysuserid/rwe; %let RAW = &ROOT/raw;",
     "options dlcreatedir; libname rawdir \"&ROOT/raw\"; libname rawdir clear; libname rwe \"&ROOT/lib\";",
     "data rwe.htn_codes; length code $7; input code :$7. @@; datalines;", " ".join(htn), ";", "run;",
     "data rwe.ndc_map; length cls $20 ndc11 $11 ahtn_class $20; infile datalines truncover; input cls :$20. @;",
     "do until(missing(ndc11)); input ndc11 :$11. @; if not missing(ndc11) then do; ahtn_class = cls; output; end; end; drop cls; datalines;"]
for cls, g in ndc.groupby("ahtn_class"):
    codes = g.ndc11.tolist()
    for i in range(0, len(codes), 20): L.append(cls + " " + " ".join(codes[i:i + 20]))
L += [";", "run;",
      "data rwe.r_attr; infile datalines dlm='|' dsd truncover; input step n_episodes n_persons; datalines;"]
L += [f"{int(r.step)}|{'' if pd.isna(r.n_episodes) else int(r.n_episodes)}|{int(r.n_persons)}" for r in att.itertuples()]
L += [";", "run;", "data rwe.r_base; infile datalines dlm='|' dsd truncover; length arm $10 variable $20 level $20; input arm variable level n; datalines;"]
L += [f"{r.arm}|{r.variable}|{r.level}|{r.n}" for r in base.itertuples()]
L += [";", "run;", "proc sql; select 'htn_codes' as ds, count(*) as n from rwe.htn_codes union all select 'ndc_map', count(*) from rwe.ndc_map union all select 'r_attr', count(*) from rwe.r_attr union all select 'r_base', count(*) from rwe.r_base; quit;"]
(root / "sas/inputs_codelists.sas").write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote sas/inputs_codelists.sas:", len(ndc), "NDC-class rows,", len(htn), "ICD codes,", len(att), "attrition rows,", len(base), "baseline rows")
